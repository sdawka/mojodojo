def implications(gemm, best_gpu, ceil) -> str:
    def b(pred):
        rr = [r for r in gemm if pred(r)]
        return max(rr, key=lambda r: r["median"]) if rr else None

    pre16 = b(lambda r: r["M"] == 512 and r["_path"] in ("mlx_nax", "max_mma") and r["dtype"] in ("bf16", "f16", "bfloat16", "float16"))
    prei8 = b(lambda r: r["M"] == 512 and r.get("kernel") == "apple_int8_w8a8")
    pre_na = b(lambda r: r["M"] == 512 and r["_path"] in ("mlx_nonax", "max_8x8"))
    pre_sme = b(lambda r: r["M"] == 512 and r["_path"] == "sme")
    pre_ane = b(lambda r: r["M"] == 512 and r["_path"] == "ane")
    dec = b(lambda r: r["M"] == 1 and r.get("eff_gbps_median") and r["engine"].startswith("gpu"))
    lines = []
    g = lambda r: f"{r['median'] / 1000:.1f} TFLOP/s ({r['_path']}, {r['dtype']}, {r['shape']})" if r else "n/a"  # noqa: E731
    lines.append(f"- **Decode is memory-bound on every engine.** The best GPU GEMV reaches "
                 f"{dec['eff_gbps_median']:.0f} GB/s effective ({dec['_path']} {dec['dtype']} {dec['shape']}), against "
                 f"{best_gpu:.0f} GB/s streaming and 153 GB/s spec. Upper bound: tok/s ≈ BW / bytes per token. For "
                 "a 3B model that is about 6.4 GB in bf16 (≈{:.0f} tok/s), 3.4 GB in 8-bit (≈{:.0f}) and 1.8 GB in "
                 "4-bit (≈{:.0f}). Fewer weight bytes is the main decode lever; on this chip, compute is not.".format(
                     dec["eff_gbps_median"] / 6.4, dec["eff_gbps_median"] / 3.4, dec["eff_gbps_median"] / 1.8) if dec else "- decode: n/a")
    lines.append(f"- **Prefill belongs on the GPU Neural Accelerators.** Best 16-bit M=512 result: {g(pre16)}; int8 "
                 f"W8A8: {g(prei8)}. The same GPU without NA: {g(pre_na)}. CPU SME/Accelerate: {g(pre_sme)}. ANE via "
                 f"Core ML: {g(pre_ane)}.")
    lines.append("- **Which dtype each engine wants.** GPU NA: bf16/f16 MMA, or int8 W8A8 at about 2× the f16 "
                 "rate. 4-bit weights help decode bandwidth; for prefill, MAX dequantizes them to bf16 first (M ≥ 256). "
                 "SME: f32, bf16→f32 or f16→f32 at the same FLOP rate; i8→i32 and non-widening f16 at 2×. The unit "
                 "is shared per P-cluster, so one thread saturates it. ANE: f16 activations; 8-bit or LUT-4 weights "
                 "are planned on the ANE, while per-block int4 is planned on the CPU.")
    lines.append("- **Engine split (to test in G2-M2/M3).** GPU NA for prefill and decode. Because decode is "
                 "bandwidth-bound and all engines share one memory system, moving decode to the ANE or CPU cannot "
                 "beat the GPU's bandwidth. It only helps if it overlaps work (e.g. ANE prefill of request B while "
                 "the GPU decodes A) or runs a 1B draft model for speculative decoding. CPU SME (~2 TFLOP/s f32 per "
                 "cluster) suits small side GEMMs or a draft model at M ≤ 16, where its GEMV is also bandwidth-bound.")
    lines.append("- **Roofline knee.** With about 100-150 GB/s and about 10-25 TFLOP/s on the GPU, the ridge point "
                 "is ~100-200 FLOP/B. Batched decode stays bandwidth-bound up to M ≈ 50-100 tokens per weight read "
                 "(16-bit), which is why speculative decoding (verify k tokens per weight pass) is cheap here.")
    return "\n".join(lines) + "\n"


